class QuinticBasis(nn.Module):
    """Fixed 384-element basis on [-1100, 80], returning B, B', B''.

    The outputs each have shape [384, time]. Interior knots are simple, so
    strain is C4 and its second time derivative is C2 there. At either support
    endpoint the derivatives are the one-sided derivatives from the interior.
    """

    def __init__(self):
        super().__init__()
        self.count, self.low, self.high = 384, -1100.0, 80.0
        self.register_buffer("knots", torch.tensor(_KNOTS, dtype=torch.float64))

    def forward(self, times: torch.Tensor):
        if times.ndim != 1 or not times.is_floating_point():
            raise ValueError('times must be a one-dimensional floating tensor')
        if bool(torch.any(~torch.isfinite(times))) or bool(torch.any((times < self.low) | (times > self.high))):
            raise ValueError('time outside declared basis support')
        knots = self.knots.to(device=times.device, dtype=times.dtype)
        x = times[None, :]
        # Choose the last nonzero interval at the closed right endpoint.
        rightmost = (knots[1:] == self.high) & (knots[:-1] < self.high)
        level = ((x >= knots[:-1, None]) & (x < knots[1:, None]) | (x == self.high) & rightmost[:, None]).to(times.dtype)
        (d1, d2) = (torch.zeros_like(level), torch.zeros_like(level))
        for degree in range(1, 6):
            size = len(knots) - degree - 1
            dl = knots[degree:degree + size] - knots[:size]
            dr = knots[degree + 1:degree + size + 1] - knots[1:size + 1]
            # Repeated endpoint knots never evaluate a zero denominator.
            il = torch.where(dl != 0, 1 / torch.where(dl != 0, dl, torch.ones_like(dl)), 0)[:, None]
            ir = torch.where(dr != 0, 1 / torch.where(dr != 0, dr, torch.ones_like(dr)), 0)[:, None]
            next_level = (x - knots[:size, None]) * il * level[:size] + (knots[degree + 1:degree + size + 1, None] - x) * ir * level[1:size + 1]
            next_d1 = degree * (il * level[:size] - ir * level[1:size + 1])
            next_d2 = degree * (il * d1[:size] - ir * d1[1:size + 1])
            (level, d1, d2) = (next_level, next_d1, next_d2)
        return (level, d1, d2)
